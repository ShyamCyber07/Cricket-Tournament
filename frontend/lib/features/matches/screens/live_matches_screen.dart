                _buildTeamLogo(t2Logo, t2Name),
              ],
            ),
            const SizedBox(height: 12),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Text(
                  "Venue: ${match['venue'] ?? 'Stadium'}",
                  style: GoogleFonts.outfit(fontSize: 12, color: AppColors.textSecondary),
                ),
                Text(
                  "Overs: ${match['over_limit']}",
                  style: GoogleFonts.outfit(fontSize: 12, color: AppColors.textSecondary, fontWeight: FontWeight.bold),
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildCompletedMatchCard(dynamic match) {
    final t1Name = match['team1_name'] ?? 'Team 1';
    final t2Name = match['team2_name'] ?? 'Team 2';
    final t1Logo = match['team1_logo_url'];
    final t2Logo = match['team2_logo_url'];
    
    final t1Runs = match['team1_runs'] ?? 0;
    final t1Wickets = match['team1_wickets'] ?? 0;
    final t1Overs = match['team1_overs'] ?? 0.0;
    final t2Runs = match['team2_runs'] ?? 0;
    final t2Wickets = match['team2_wickets'] ?? 0;
    final t2Overs = match['team2_overs'] ?? 0.0;

    String resultText = match['win_margin_text'] ?? "Match Completed";

    return InkWell(
      onTap: () async {
        await Navigator.push(
          context,
          MaterialPageRoute(builder: (context) => ScorecardScreen(matchId: match['id'])),
        );
      },
      child: Container(
        margin: const EdgeInsets.only(bottom: 12),
        padding: const EdgeInsets.all(16),
        decoration: AppColors.glassDecoration(borderRadius: BorderRadius.circular(16)),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Text(
                  "Tournament: ${match['tournament_name'] ?? 'League'}",
                  style: GoogleFonts.outfit(color: AppColors.textSecondary, fontSize: 11, fontWeight: FontWeight.bold),
                ),
                Container(
                  padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                  decoration: BoxDecoration(
                    color: (match['status'] == 'abandoned' ? Colors.grey : (match['status'] == 'no_result' ? Colors.redAccent : Colors.blueAccent)).withOpacity(0.12),
                    borderRadius: BorderRadius.circular(6),
                  ),
                  child: Text(
                    (match['status']?.toString().toUpperCase() ?? 'COMPLETED'),
                    style: GoogleFonts.outfit(
                      color: match['status'] == 'abandoned' ? Colors.grey : (match['status'] == 'no_result' ? Colors.redAccent : Colors.blueAccent),
                      fontSize: 10,
                      fontWeight: FontWeight.bold,
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            Row(
              children: [
                _buildTeamLogo(t1Logo, t1Name),
                const SizedBox(width: 10),
                Expanded(
                  child: Text(
                    t1Name,
                    style: GoogleFonts.outfit(fontWeight: FontWeight.w600, color: Colors.white),
                  ),
                ),
                Text(
                  "$t1Runs/$t1Wickets ($t1Overs)",
                  style: GoogleFonts.outfit(fontWeight: FontWeight.bold, color: Colors.white),
                ),
              ],
            ),
            const SizedBox(height: 8),
            Row(
              children: [
                _buildTeamLogo(t2Logo, t2Name),
                const SizedBox(width: 10),
                Expanded(
                  child: Text(
                    t2Name,
                    style: GoogleFonts.outfit(fontWeight: FontWeight.w600, color: Colors.white),
                  ),
                ),
                Text(
                  "$t2Runs/$t2Wickets ($t2Overs)",
                  style: GoogleFonts.outfit(fontWeight: FontWeight.bold, color: Colors.white),
                ),
              ],
            ),
            const Divider(color: Colors.white10, height: 20),
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Expanded(
                  child: Text(
                    resultText,
                    style: GoogleFonts.outfit(fontSize: 12, color: AppColors.primary, fontWeight: FontWeight.bold),
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
                const Icon(Icons.arrow_forward_ios_rounded, color: AppColors.textSecondary, size: 12),
              ],
            ),
          ],
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    // Categorize tournament matches
    final liveMatches = _matches.where((m) {
      final status = m['status'];
      return status == 'innings1' || status == 'innings2' || status == 'team_selection' || 
             status == 'toss' || status == 'ready' || status == 'live' || status == 'innings_break';
    }).toList();

    final upcomingMatches = _matches.where((m) => m['status'] == 'scheduled').toList();
    final completedMatches = _matches.where((m) => m['status'] == 'completed' || m['status'] == 'abandoned' || m['status'] == 'no_result').toList();

    return Scaffold(
      appBar: AppBar(
        title: const Text("Tournament Matches"),
        bottom: TabBar(
          controller: _tabController,
          indicatorColor: AppColors.primary,
          labelColor: AppColors.primary,
          unselectedLabelColor: Colors.white60,
          tabs: const [
            Tab(text: "LIVE"),
            Tab(text: "UPCOMING"),
            Tab(text: "COMPLETED"),
          ],
        ),
      ),
      body: RefreshIndicator(
        onRefresh: _fetchMatches,
        color: AppColors.primary,
        backgroundColor: AppColors.surface,
        child: _isLoading
            ? const Center(child: NeonBallOrbitLoader())
            : TabBarView(
                controller: _tabController,
                children: [
                  // Tab 1: Live Matches
                  liveMatches.isEmpty
                      ? _buildEmptyState("No live matches are currently in progress. Start one from the scheduled fixtures!")
                      : ListView.builder(
                          padding: const EdgeInsets.all(16.0),
                          itemCount: liveMatches.length,
                          itemBuilder: (context, index) => _buildLiveMatchCard(liveMatches[index]),
                        ),
                  
                  // Tab 2: Upcoming Matches
                  upcomingMatches.isEmpty
                      ? _buildEmptyState("No upcoming matches scheduled. Organizer needs to generate and publish fixtures!")
                      : ListView.builder(
                          padding: const EdgeInsets.all(16.0),
                          itemCount: upcomingMatches.length,
                          itemBuilder: (context, index) => _buildUpcomingMatchCard(upcomingMatches[index]),
                        ),

                  // Tab 3: Completed Matches
                  completedMatches.isEmpty
                      ? _buildEmptyState("No completed matches found in this tournament.")
                      : ListView.builder(
                          padding: const EdgeInsets.all(16.0),
                          itemCount: completedMatches.length,
                          itemBuilder: (context, index) => _buildCompletedMatchCard(completedMatches[index]),
                        ),
                ],
              ),
      ),
    );
  }
}